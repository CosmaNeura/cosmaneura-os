import Foundation

/// A generation belongs to one bridge, never to a retry of its document.
struct WorkspaceRecoveryState {
    enum Phase: Equatable { case opening, active, failed }
    enum Signal: String { case ready, failed }
    enum StopState: Equatable { case unchecked, checking, blocked, idle }

    let generation: String
    private(set) var phase: Phase = .opening
    private(set) var stopState: StopState = .unchecked
    private(set) var remainingForegroundSeconds: TimeInterval
    private var activeSince: TimeInterval?

    init(generation: String = UUID().uuidString, timeout: TimeInterval = 45) {
        self.generation = generation
        remainingForegroundSeconds = timeout
    }

    mutating func receive(_ signal: Signal, generation: String,
                          mainFrame: Bool, sameOrigin: Bool) -> Bool {
        guard mainFrame, sameOrigin, generation == self.generation, phase != .failed else { return false }
        switch signal {
        case .ready:
            guard phase == .opening else { return false }
            phase = .active
            activeSince = nil
        case .failed: fail()
        }
        return true
    }

    @discardableResult mutating func fail() -> Bool {
        guard phase != .failed else { return false }
        phase = .failed
        activeSince = nil
        return true
    }

    /// Called on both activity transitions and timer ticks; background time is excluded.
    mutating func tick(now: TimeInterval, sceneActive: Bool) -> Bool {
        guard phase == .opening else { return false }
        if let previous = activeSince { remainingForegroundSeconds -= max(0, now - previous) }
        activeSince = sceneActive ? now : nil
        if remainingForegroundSeconds <= 0 { return fail() }
        return false
    }

    mutating func beginStopCheck() -> Bool {
        guard phase == .failed, stopState != .checking else { return false }
        stopState = .checking
        return true
    }

    mutating func finishStopCheck(idle: Bool) {
        guard phase == .failed, stopState == .checking else { return }
        stopState = idle ? .idle : .blocked
    }

    var canReopen: Bool { phase == .failed && stopState == .idle }
}

/// Only the native-admitted selected document expands its compiled policy.
/// The bundled beta document and every non-connect directive remain unchanged.
enum WorkspaceRegisteredDocumentPolicy {
    enum Invalid: Error { case document, origin }

    static func selectedHTML(_ source: String, apiOrigin: String) throws -> String {
        guard source.utf8.count <= 1_048_576,
              exactHTTPS(apiOrigin),
              apiOrigin.range(of: #"^https://api\.[a-z0-9](?:[a-z0-9-]*[a-z0-9])?\.staging\.cosmas\.ai$"#,
                options: .regularExpression) != nil else { throw Invalid.origin }
        // This exact tag is generated by prepare-apple-synthetic.py. Never
        // append a second meta policy, which cannot relax the first policy.
        let opening = "<meta http-equiv=\"Content-Security-Policy\" content=\""
        let closing = "\" />"
        guard source.components(separatedBy: "Content-Security-Policy").count == 2,
              source.lowercased().components(separatedBy: "content-security-policy").count == 2,
              let start = source.range(of: opening),
              let end = source.range(of: closing, range: start.upperBound..<source.endIndex),
              let head = source.range(of: "<head>", options: .caseInsensitive),
              let headEnd = source.range(of: "</head>", options: .caseInsensitive),
              head.upperBound <= start.lowerBound, end.upperBound < headEnd.lowerBound,
              source.range(of: #"<(?:script|link|base|img|iframe|body)(?:\s|>)"#,
                options: [.regularExpression, .caseInsensitive], range: source.startIndex..<start.lowerBound) == nil else {
            throw Invalid.document
        }
        let content = String(source[start.upperBound..<end.lowerBound])
        guard !content.contains("<"), !content.contains(">"), !content.contains("\"") else { throw Invalid.document }
        let decoded = content.replacingOccurrences(of: "&#x27;", with: "'")
            .replacingOccurrences(of: "&#39;", with: "'")
        guard !decoded.contains("&") else { throw Invalid.document }
        let values = decoded.split(separator: ";", omittingEmptySubsequences: false).map(String.init)
        let names = values.map { $0.split(whereSeparator: { $0.isWhitespace }).first.map(String.init) ?? "" }
        guard names.filter({ $0 == "connect-src" }).count == 1,
              let index = names.firstIndex(of: "connect-src"),
              names.filter({ !$0.isEmpty }).count == Set(names.filter({ !$0.isEmpty })).count else { throw Invalid.document }
        let tokens = values[index].split(whereSeparator: { $0.isWhitespace }).map(String.init)
        guard tokens.count >= 2, tokens.count <= 8, tokens[0] == "connect-src", tokens[1] == "'self'",
              tokens.dropFirst(2).allSatisfy(exactHTTPS), Set(tokens).count == tokens.count else { throw Invalid.document }
        if tokens.contains(apiOrigin) { return source }
        // HTML quote entities themselves end with ';'. Split actual CSP
        // directive separators without changing the original encoded bytes.
        var raw = rawDirectives(content)
        guard raw.count == values.count else { throw Invalid.document }
        let original = raw[index]
        let trailing = String(original.reversed().prefix(while: { $0.isWhitespace }).reversed())
        raw[index] = String(original.dropLast(trailing.count)) + " " + apiOrigin + trailing
        return String(source[..<start.upperBound]) + raw.joined(separator: ";") + String(source[end.lowerBound...])
    }

    private static func exactHTTPS(_ value: String) -> Bool {
        guard value.utf8.count <= 253, let url = URLComponents(string: value),
              url.scheme == "https", let host = url.host, host == host.lowercased(),
              url.port == nil, url.user == nil, url.password == nil,
              url.path.isEmpty, url.query == nil, url.fragment == nil,
              host.range(of: #"^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]*[a-z0-9])?)+$"#,
                options: .regularExpression) != nil else { return false }
        return url.string == value
    }

    private static func rawDirectives(_ content: String) -> [String] {
        var result: [String] = [], start = content.startIndex, cursor = content.startIndex
        while cursor < content.endIndex {
            if content[cursor...].hasPrefix("&#x27;") { cursor = content.index(cursor, offsetBy: 6); continue }
            if content[cursor...].hasPrefix("&#39;") { cursor = content.index(cursor, offsetBy: 5); continue }
            if content[cursor] == ";" {
                result.append(String(content[start..<cursor])); start = content.index(after: cursor)
            }
            cursor = content.index(after: cursor)
        }
        result.append(String(content[start...])); return result
    }
}
