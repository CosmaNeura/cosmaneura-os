"""Summarize observed clinician runs without substituting UX claims for receipts."""

import argparse
import html
import json
import statistics
from pathlib import Path

PERSONAS = ("provider", "nurse", "pa")


def summarize(root):
    rows = []
    for round_number in (1, 2):
        for persona in PERSONAS:
            path = root / f"{persona}-{round_number}.json"
            if not path.exists():
                rows.append({"persona": persona, "round": round_number, "status": "not_completed"})
                continue
            result = json.loads(path.read_text())
            receipts = result.get("handoff_receipts", [])
            artifacts = result.get("artifacts", [])
            plan = next((item.get("structured_plan", {}) for item in artifacts if item.get("role") == "chief_plan"), {})
            expected_roles = {task.get("owner") for task in plan.get("tasks", [])}
            checked = {
                "workflow_checks": result.get("passed") is True and all(result.get("checks", {}).values()),
                "three_saved_recipient_replies": len(receipts) == 3 and all(item.get("status") == "completed"
                    and item.get("result_entry_id") for item in receipts),
                "correct_recipients": len(expected_roles) == 3 and expected_roles <= {"visit_prep", "scribe", "research", "follow_up"}
                    and {item.get("recipient_role") for item in receipts} == expected_roles,
                "one_attempt_each": all(item.get("attempt_count") == 1 for item in receipts),
                "chief_plan_results_and_verification": len(artifacts) == 5,
                "no_external_effects": result.get("application", {}).get("external_effects") == 0,
            }
            rows.append({"persona": persona, "round": round_number,
                "status": "passed" if all(checked.values()) else "failed", "checks": checked,
                "duration_ms": result["duration_ms"], "phase_ms": result["timing"]["phase_ms"],
                "queue_ms": result["timing"]["recipient_queue_ms"],
                "recipient_execution_ms": result["timing"]["recipient_execution_ms"],
                "tool_calls": result["tool_calls"], "failures": result["failures"],
                "saved_reply_ids": [item.get("result_entry_id") for item in receipts],
                "evidence": path.name})
    events = [json.loads(line) for line in (root / "events.jsonl").read_text().splitlines()]
    model = [row for row in events if row["kind"] == "model"]
    completed = [row for row in rows if row["status"] == "passed"]
    return {"schema": "cosmabot-clinician-runs.v1", "mode": "real_model" if model else "replay",
        "synthetic_only": True, "complete": len(completed) == 6, "rows": rows,
        "model_calls": len(model), "verified_tokens": sum(row.get("total_tokens", 0) for row in model),
        "median_workflow_ms": statistics.median(row["duration_ms"] for row in completed) if completed else None,
        "evidence_limits": [
            "Workflow pass requires real saved replies, attribution and exact duplicate recovery.",
            "Usability findings are separate persona observations; service success is not unassisted clinician success.",
            "The production encounter UI and saved-work services are connected to an explicit laboratory model dispatcher, not the installed release's complete background worker.",
            "UI action timings and agent deliberation are not human dwell time.",
            "Transcript dialogue is invented; the Scribe summary is generated by the indicated model. No recording or speech recognition is tested.",
            "Research prepares a source-bound investigation draft; no public trial search or eligibility decision occurs.",
            "Private drafts require clinician review. No external messaging, booking, clinical signature or delivery occurs.",
        ]}


def write(root):
    value = summarize(root)
    (root / "run-summary.json").write_text(json.dumps(value, indent=2) + "\n")
    cells = []
    for row in value["rows"]:
        times = row.get("phase_ms", {})
        cells.append("<tr>" + "".join("<td>" + html.escape(str(item)) + "</td>" for item in (
            row["persona"].title(), row["round"], row["status"],
            f"{row['duration_ms']/1000:.2f}s" if "duration_ms" in row else "—",
            *(f"{times[key]/1000:.2f}s" if key in times else "—" for key in ("chief_plan", "recipient_work", "chief_review")))) + "</tr>")
    document = """<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>CosmaBot clinician handoff runs</title><style>body{font:16px system-ui;color:#18342b;background:#f6f8f5;max-width:1100px;margin:40px auto;padding:0 24px}h1{font-size:28px}table{border-collapse:collapse;width:100%;background:white}th,td{padding:12px;text-align:left;border-bottom:1px solid #dce4df}th{font-size:13px}li{margin:9px 0}.status{padding:16px;background:#e2eee4;border-radius:10px}small{color:#52645c}</style>
<h1>🧭 Clinician → Chief → saved team work</h1><p class="status">"""
    document += f"{sum(row['status']=='passed' for row in value['rows'])} of 6 saved-work checks passed. {value['model_calls']} measured model calls. This is separate from clinician usability acceptance.</p>"
    document += "<p>Invented encounter · Provider, nurse and PA · Two rounds · Actual local saved-work services</p><table><thead><tr><th>Persona</th><th>Round</th><th>Workflow</th><th>Total</th><th>Chief plan</th><th>Team drafts</th><th>Chief verification</th></tr></thead><tbody>" + "".join(cells) + "</tbody></table>"
    document += "<p><small>Times measure system work, not human time on task. Persona usability findings are retained separately.</small></p><ul>"
    document += "".join("<li>" + html.escape(item) + "</li>" for item in value["evidence_limits"]) + "</ul></html>"
    (root / "run-summary.html").write_text(document)
    return value


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("root", type=Path)
    args = parser.parse_args()
    result = write(args.root)
    print(json.dumps({"complete": result["complete"], "rows": [{key: row.get(key) for key in
          ("persona", "round", "status", "duration_ms")} for row in result["rows"]],
          "model_calls": result["model_calls"], "verified_tokens": result["verified_tokens"]}))


if __name__ == "__main__":
    main()
